// sur le globe.
//
// Embarqués plutôt que récupérés en ligne : la carte ne doit dépendre d'aucun
// appel réseau au moment de l'affichage, et un GeoJSON mondial pèse plusieurs
// mégaoctets pour un rendu en points qui n'en a pas besoin.
//
// La précision visée est le pays, pas la ville : ces coordonnées servent à
// poser un repère sur un globe, jamais à localiser quoi que ce soit.
//
